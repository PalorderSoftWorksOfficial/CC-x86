local CPU=require("src.x86.core.cpu")
local function load(cpu,bytes,base)
 for i=1,#bytes do cpu.memory:write_u8(base+i-1,bytes[i]) end
 cpu:reset(base,0x7000)
end
local function run(cpu,bytes,base)
 load(cpu,bytes,base)
 cpu:run(1000)
end
local cpu=CPU.new({memory_size=1024*1024,terminal={write=function(self,value,width) self.value=value end}})
local base=0x1000
cpu.flags:set(cpu.flags.CF,true)
run(cpu,{0xB8,1,0,0,0,0x40,0xF4},base)
assert(cpu.registers:get(0)==2)
assert(cpu.flags:has(cpu.flags.CF))
load(cpu,{0x8D,0x54,0x8B,0x10,0xF4},base)
cpu.registers:set(3,0x100)
cpu.registers:set(1,3)
cpu:run(10)
assert(cpu.registers:get(2)==0x11C)
run(cpu,{0x31,0xC0,0x0F,0x84,5,0,0,0,0xB8,1,0,0,0,0xF4},base)
assert(cpu.registers:get(0)==0)
run(cpu,{0xB8,3,0,0,0,0xBB,4,0,0,0,0x0F,0xAF,0xC3,0xF4},base)
assert(cpu.registers:get(0)==12)
run(cpu,{0xB8,0,0,0,0,0x0F,0xA2,0xF4},base)
assert(cpu.registers:get(0)==1)
assert(cpu.registers:get(1)~=0)
run(cpu,{0xB8,65,0,0,0,0xE6,0xE9,0xF4},base)
assert(cpu.bus.ports[0xE9].value==65)
run(cpu,{0x0F,0x31,0xF4},base)
assert(cpu.registers:get(0)>=0)
assert(cpu.registers:get(2)>=0)
cpu.memory:write_u8(0x3000,0xAB)
run(cpu,{0x0F,0xB6,0x05,0x00,0x30,0x00,0x00,0xF4},base)
assert(cpu.registers:get(0)==0xAB)
print("cc-x86 WIP feature tests passed")
